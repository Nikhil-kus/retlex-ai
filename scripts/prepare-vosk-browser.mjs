/** Prepare the pinned npm library for our own versioned Cache Storage cache.
 * Upstream mounts an IndexedDB filesystem and copies extracted models into it.
 * That fails in some embedded/private browsers, and random blob model URLs create
 * duplicate copies. Our loader already caches + verifies the compressed model.
 * Keep the worker filesystem in memory and preserve the recognition code.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
const require = createRequire(import.meta.url);
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const packageInfo = require('vosk-browser/package.json');
if (packageInfo.version !== '0.0.8') throw new Error('Review the worker preparation before upgrading vosk-browser.');
let library = readFileSync(require.resolve('vosk-browser'), 'utf8');
const match = library.match(/var WorkerFactory = createBase64WorkerFactory\('([^']+)'/);
if (!match) throw new Error('Unexpected Vosk worker packaging.');
let worker = Buffer.from(match[1], 'base64').toString('utf8');
// Forward worker warnings through the existing event channel for actionable diagnostics.
worker = worker.replace("'use strict';", "'use strict';\n" +
  "for (const level of ['warn', 'error']) { const original = console[level].bind(console); console[level] = (...args) => { original(...args); self.postMessage({event: 'diagnostic', message: args.map(String).join(' ')}); }; }");
for (const [from, to] of [
  ['this.Vosk.FS.mount(this.Vosk.IDBFS, {}, storagePath);', '/* Persistence is handled by the application cache. */'],
  ['return this.Vosk.syncFilesystem(true);', 'return Promise.resolve();'],
  ['return this.Vosk.syncFilesystem(false);', 'return Promise.resolve();'],
]) {
  if (!worker.includes(from)) throw new Error('Unexpected Vosk filesystem implementation.');
  worker = worker.replace(from, to);
}
worker = worker.replaceAll('error: error.message', 'error: error.message || String(error)');
library = library.replace(match[1], Buffer.from(worker).toString('base64'));
// Hard termination also works when initialization fails before a model exists.
const termination = /this\.postMessage\(\{\s*action: "terminate",\s*\}\);/;
if (!termination.test(library)) throw new Error('Unexpected Vosk termination implementation.');
library = library.replace(termination, 'this.worker.terminate();');
const dest = resolve(root, 'public/voice');
mkdirSync(dest, { recursive: true });
writeFileSync(resolve(dest, 'vosk-browser-0.0.8.js'),
  '/* vosk-browser 0.0.8, Apache-2.0. Generated by scripts/prepare-vosk-browser.mjs.\n' +
  ' * Source: https://github.com/ccoreilly/vosk-browser\n' +
  ' * Modifications: application-managed persistence, robust errors and termination. */\n' + library);
console.log('Prepared Vosk browser runtime with application-managed model caching.');
